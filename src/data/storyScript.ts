export function getActiveSceneAtTime(
  script: StoryScript,
  timeSeconds: number
): { scene: StoryScript['scenes'][number]; sceneElapsed: number; sceneProgress: number } {
  const clamped = Math.max(0, Math.min(script.totalDuration - 0.001, timeSeconds));
  const found =
    script.scenes.find(
      (s) => clamped >= s.startTime && clamped < s.startTime + s.duration
    ) || script.scenes[script.scenes.length - 1];

  const sceneElapsed = Math.max(0, clamped - found.startTime);
  const sceneProgress = Math.min(1, Math.max(0, sceneElapsed / found.duration));
  return { scene: found, sceneElapsed, sceneProgress };
}
